//! Markdown "legend file": a printable briefing the operator studies before
//! going live.

use std::fmt::Write;

use crate::UiLang;
use crate::labels::label;
use crate::model::Persona;

pub fn markdown(p: &Persona, lang: UiLang) -> String {
    let fr = lang == UiLang::Fr;
    let t = |f: &'static str, e: &'static str| if fr { f } else { e };
    let id = &p.identity;
    let mut s = String::new();
    let _ = writeln!(s, "# {} — {}", p.codename.get(lang), id.full_name());
    let _ = writeln!(s);
    let _ = writeln!(
        s,
        "> {}",
        t(
            "Identité fictive générée par SIMULACRE. Usage : enquête OSINT, recherche, formation. Ne pas utiliser pour usurper une personne réelle.",
            "Fictional identity generated by SIMULACRE. Use: OSINT investigations, research, training. Do not use to impersonate a real person."
        )
    );
    let _ = writeln!(s);
    let _ = writeln!(s, "`seed {}` · `{}` · {} {}/100", p.recipe.seed, p.locale.code, t("cohérence", "coherence"), p.coherence.score);
    let _ = writeln!(s);
    let _ = writeln!(s, "## {}", t("Fiche", "Card"));
    let rows: Vec<(&str, String)> = vec![
        (t("Nom", "Name"), id.full_name()),
        (t("Surnom", "Nickname"), id.nickname.clone().unwrap_or_else(|| "—".into())),
        (t("Naissance", "Born"), format!("{} — {}", id.birth_date.format("%d/%m/%Y"), id.birthplace.city)),
        (t("Âge", "Age"), id.age.to_string()),
        (t("Ville", "City"), format!("{} ({}) — {}", p.residence.place.city, p.residence.district, p.residence.place.region)),
        (t("Statut", "Status"), label("status", &p.occupation.status, lang)),
        (
            t("Poste", "Job"),
            match (&p.occupation.title, &p.occupation.employer) {
                (Some(t), Some(e)) => format!("{t} — {e}"),
                (Some(t), None) => t.clone(),
                _ => "—".into(),
            },
        ),
        (t("Situation", "Relationship"), label("relationship", &p.family.relationship, lang)),
        (
            t("Téléphone", "Phone"),
            p.contact
                .phone
                .clone()
                .map(|ph| format!("{ph} ({})", t("plage réservée fiction, non attribuée", "fiction-reserved range, not assigned")))
                .unwrap_or_else(|| t("à fournir", "to provide").into()),
        ),
        (t("Profil", "Type"), label("ptype", &p.personality.type_key, lang)),
    ];
    let _ = writeln!(s, "| | |\n|---|---|");
    for (k, v) in rows {
        let _ = writeln!(s, "| **{k}** | {} |", v.replace('|', "\\|"));
    }
    let _ = writeln!(s);
    let _ = writeln!(s, "## {}", t("Histoire", "Backstory"));
    let _ = writeln!(s, "{}", p.narrative.get(lang));
    let _ = writeln!(s);
    let _ = writeln!(s, "## {}", t("Pitch (30 secondes)", "Elevator pitch"));
    let _ = writeln!(s, "> {}", p.legend.pitch.get(lang));
    let _ = writeln!(s);
    let _ = writeln!(s, "## {}", t("Chronologie", "Timeline"));
    for e in &p.timeline {
        let _ = writeln!(s, "- **{}** — {}", e.year, e.text.get(lang));
    }
    let _ = writeln!(s);
    let _ = writeln!(s, "## {}", t("Comptes", "Accounts"));
    for a in &p.accounts {
        let h = a.handle.as_ref().map(|h| format!("@{h}")).unwrap_or_else(|| a.display_name.clone());
        let _ = writeln!(
            s,
            "- **{}** {} — {} · {:.1}/{} · {} {}",
            a.platform_name,
            h,
            label("activity", &a.activity, lang),
            a.posts_per_week,
            t("sem.", "wk"),
            t("depuis", "since"),
            a.claimed_since
        );
        if !a.bio.is_empty() {
            let _ = writeln!(s, "  - _{}_", a.bio);
        }
    }
    let _ = writeln!(s);
    let _ = writeln!(s, "## {}", t("Voix", "Voice"));
    for post in &p.voice {
        let _ = writeln!(
            s,
            "- [{} {:02}:{:02} · {}] {}",
            label("weekday", &post.weekday.to_string(), lang),
            post.hour,
            post.minute,
            post.platform,
            post.text
        );
    }
    let _ = writeln!(s);
    for (title, items) in [
        (t("Points d'appui", "Talking points"), &p.legend.talking_points),
        (t("Points faibles", "Weak spots"), &p.legend.weak_spots),
        (t("Hygiène opérationnelle", "Opsec"), &p.legend.opsec),
    ] {
        let _ = writeln!(s, "## {title}");
        for i in items {
            let _ = writeln!(s, "- {}", i.get(lang));
        }
        let _ = writeln!(s);
    }
    let _ = writeln!(s, "## {}", t("Cohérence", "Coherence"));
    for c in &p.coherence.checks {
        let _ = writeln!(s, "- `{:?}` {}", c.severity, c.message.get(lang));
    }
    s
}
